<?php
require_once '../config/db.php';
require_once '../includes/auth/auth_helper.php';
checkAccess('admin, superadmin');

$date_to_export = isset($_GET['date']) ? $_GET['date'] : date('Y-m-d');
$dept_to_export = isset($_GET['dept']) ? $_GET['dept'] : 'All';

// Build Query
$where_dept = ($dept_to_export !== 'All') ? " AND t.department = :dept" : "";
$params = [':date' => $date_to_export];
if ($dept_to_export !== 'All') $params[':dept'] = $dept_to_export;

// Set headers para sa Excel
header("Content-Type: application/vnd.ms-excel");
header("Content-Disposition: attachment; filename=QUEST_OJT_REPORT_" . strtoupper($dept_to_export) . "_" . $date_to_export . ".xls");
header("Pragma: no-cache");
header("Expires: 0");

$stmt = $pdo->prepare("
    SELECT a.*, t.first_name, t.last_name, t.department 
    FROM attendance a 
    JOIN trainees t ON a.trainee_id = t.id 
    WHERE a.date = :date
" . $where_dept . "
    ORDER BY t.department ASC, t.last_name ASC
");
$stmt->execute($params);
$logs = $stmt->fetchAll();
